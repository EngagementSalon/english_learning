// 当前语言（默认中文）
let LANG = 'zh'
function getLang() { return LANG }
function setLang(lang) {
  LANG = (lang === 'en') ? 'en' : 'zh'
  try { localStorage.setItem('eq_lang', LANG) } catch (e) { /* ignore */ }
}
function loadLang() {
  try {
    const saved = localStorage.getItem('eq_lang')
    LANG = saved === 'en' ? 'en' : 'zh'
  } catch (e) { LANG = 'zh' }
  return LANG
}
// 取词：t('key') 或 t('key', arg)
function t(key) {
  const dict = I18N[LANG] || I18N.zh
  let v = dict[key]
  if (v === undefined) v = I18N.zh[key]
  if (v === undefined) return key
  if (typeof v === 'function') return v.apply(null, [].slice.call(arguments, 1))
  return v
}
// 切换语言并刷新界面
function toggleLang() {
  setLang(LANG === 'zh' ? 'en' : 'zh')
  renderStaticText()
  // 刷新当前页面内容（重新渲染当前激活的 page）
  if (typeof navigate === 'function') {
    const active = document.querySelector('.nav-item.active')
    const page = active ? active.dataset.page : 'home'
    // 若在登录界面则不需要重渲染 page
    const appEl = document.getElementById('app')
    if (appEl && appEl.style.display !== 'none') navigate(page)
  }
}
